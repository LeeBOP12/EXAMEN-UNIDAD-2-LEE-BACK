create table ag_privilegios (
    id number(19,0) generated by default as identity,
    nombre varchar2(50 char) not null,
    constraint pk_ag_privilegios primary key (id),
    constraint ux_ag_privilegios_nombre unique (nombre)
);
create table ag_roles (
    id number(19,0) generated by default as identity,
    nombre varchar2(40 char) not null,
    descripcion varchar2(180 char),
    constraint pk_ag_roles primary key (id),
    constraint ux_ag_roles_nombre unique (nombre)
);
create table ag_rol_privilegio (
    rol_id number(19,0) not null, privilegio_id number(19,0) not null,
    constraint pk_ag_rol_privilegio primary key (rol_id, privilegio_id),
    constraint fk_ag_rp_rol foreign key (rol_id) references ag_roles (id),
    constraint fk_ag_rp_priv foreign key (privilegio_id) references ag_privilegios (id)
);
create table ag_usuarios (
    id number(19,0) generated by default as identity,
    username varchar2(50 char) not null, password varchar2(100 char) not null,
    nombre varchar2(120 char) not null, estado boolean not null,
    constraint pk_ag_usuarios primary key (id)
);
create unique index ux_ag_usuarios_username on ag_usuarios (upper(username));
create table ag_usuario_rol (
    usuario_id number(19,0) not null, rol_id number(19,0) not null,
    constraint pk_ag_usuario_rol primary key (usuario_id, rol_id),
    constraint fk_ag_ur_usuario foreign key (usuario_id) references ag_usuarios (id),
    constraint fk_ag_ur_rol foreign key (rol_id) references ag_roles (id)
);
create table ag_lotes (
    id number(19,0) generated by default as identity,
    codigo varchar2(20 char) not null, nombre varchar2(120 char) not null,
    hectareas number(10,2) not null, cultivo varchar2(80 char) not null,
    valle varchar2(80 char) not null, campania_cerrada boolean not null,
    dosis_maxima_por_hectarea number(10,2) not null,
    constraint pk_ag_lotes primary key (id), constraint ux_ag_lotes_codigo unique (codigo)
);
create index ix_ag_lotes_valle on ag_lotes (valle);
create table ag_labores (
    id number(19,0) generated by default as identity,
    lote_id number(19,0) not null, tipo varchar2(20 char) not null,
    fecha date not null, responsable_id number(19,0) not null,
    cantidad number(12,2) not null, observacion varchar2(500 char) not null,
    fecha_registro timestamp(6) not null,
    constraint pk_ag_labores primary key (id),
    constraint fk_ag_labor_lote foreign key (lote_id) references ag_lotes (id),
    constraint fk_ag_labor_usuario foreign key (responsable_id) references ag_usuarios (id),
    constraint ck_ag_labor_tipo check (tipo in ('RIEGO','FUMIGACION','COSECHA')),
    constraint ck_ag_labor_cantidad check (cantidad > 0)
);
create index ix_ag_labores_lote_fecha on ag_labores (lote_id, fecha);
